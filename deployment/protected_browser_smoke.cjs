const assert=require('node:assert/strict');
const {chromium}=require('playwright-core');
const url=process.env.RF_PROTECTED_BROWSER_URL;
const password=process.env.RF_PROTECTED_BROWSER_PASSWORD;
if(!url||!password)throw Error('Disposable protected browser fixture missing');
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  try{
    const teacher=await browser.newContext(),monitor=await browser.newContext(),other=await browser.newContext();
    async function login(ctx,user){
      const page=await ctx.newPage();
      await page.route('**/*',route=>route.request().url().startsWith(url+'/')?route.continue():route.abort());
      await page.goto(url+'/login/');
      await page.locator('#username').fill(user);
      await page.locator('#password').fill(password);
      await Promise.all([page.waitForURL('**/live/'),page.getByRole('button',{name:'Sign in'}).click()]);
      return page;
    }
    const t=await login(teacher,'browser_teacher');
    const m=await login(monitor,'browser_monitor');
    const o=await login(other,'browser_other');
    const lesson='/live/roll/?code=BROWSER7&period=P1&start=00%3A00';
    assert.equal((await t.goto(url+lesson)).status(),200);
    assert.match(await t.locator('main').innerText(),/BrowserAllowed/);
    assert.doesNotMatch(await t.locator('main').innerText(),/BrowserDenied/);
    assert.equal((await o.goto(url+lesson)).status(),403);
    assert.equal((await m.goto(url+lesson)).status(),403);
    assert.equal((await t.goto(url+lesson)).status(),200);
    // RC2.2 buttons update the single existing select/form value; no parallel API.
    await t.locator('.rf-mark-buttons button[data-mark="A"]').click();
    assert.equal(await t.locator('select[name^="mark_"]').inputValue(),'A');
    assert.equal(await t.locator('[data-rf-count="A"]').innerText(),'1');
    await t.locator('.rf-mark-buttons button[data-mark="P"]').focus();await t.keyboard.press('Enter');
    assert.equal(await t.locator('select[name^="mark_"]').inputValue(),'P');
    assert.equal(await t.locator('[data-rf-count="P"]').innerText(),'1');
    assert.equal(await t.locator('[data-rf-count="A"]').innerText(),'0');
    await t.locator('select[name^="mark_"]').selectOption('L');
    assert.equal(await t.locator('[data-rf-count="L"]').innerText(),'1');
    assert.equal(await t.locator('.rf-mark-buttons button[data-mark="L"]').getAttribute('aria-pressed'),'true');
    await t.locator('select[name^="mark_"]').selectOption('P');
    assert.equal(await t.locator('[data-rf-count="L"]').innerText(),'0');
    assert.equal(await t.locator('[data-rf-count="P"]').innerText(),'1');
    await t.locator('input[name="certify"]').check();
    await t.getByRole('button',{name:'Submit and lock'}).click();
    await t.getByText('This roll is locked.',{exact:false}).waitFor();
    assert.equal(await t.locator('select[name^="mark_"]').isDisabled(),true);
    assert.equal((await m.goto(url+'/live/attendance/')).status(),200);
    const r=m.locator('tr').filter({hasText:'BROWSER7'});
    assert.match(await r.innerText(),/Submitted/);
    assert.doesNotMatch(await m.locator('main').innerText(),/BrowserAllowed|BrowserDenied/);
    assert.equal((await o.goto(url+'/live/attendance/')).status(),403);
    assert.equal((await t.goto(url+'/live/teacher/classes/')).status(),200);
    assert.match(await t.locator('main').innerText(),/BROWSER7/);
    assert.doesNotMatch(await t.locator('main').innerText(),/BROWSER8/);
    await t.getByRole('link',{name:'View class'}).click();
    assert.match(await t.locator('main').innerText(),/BrowserAllowed/);
    assert.doesNotMatch(await t.locator('main').innerText(),/BrowserDenied/);
    await t.getByRole('link',{name:'View student'}).click();
    assert.match(await t.locator('main').innerText(),/BrowserAllowed/);
    assert.match(await t.locator('main').innerText(),/Today's verified lessons/);
    assert.match(await t.locator('main').innerText(),/Submitted/);
    assert.doesNotMatch(await t.locator('main').innerText(),/BrowserDenied/);
    assert.equal((await o.goto(url+'/live/teacher/classes/BROWSER7/')).status(),404);
    assert.equal((await m.goto(url+'/live/teacher/students/')).status(),403);
    await t.goto(url+'/live/day/');await t.getByRole('link',{name:'Week',exact:true}).click();
    assert.equal(await t.locator('[data-schedule-date]').count(),5);
    assert.doesNotMatch(await t.locator('main').innerText(),/BROWSER8/);
    const classroom='/live/classroom/?code=BROWSER7&period=P1&start=00%3A00';
    assert.equal((await t.goto(url+classroom)).status(),200);
    assert.equal((await o.goto(url+classroom)).status(),403);
    await t.locator('#rf-seat-student').selectOption({label:'Fictional, BrowserAllowed'});
    await t.locator('[data-seat="2"]').click();
    assert.equal(await t.locator('input[name^="seat_"]').inputValue(),'2');
    await Promise.all([t.waitForNavigation(),t.getByRole('button',{name:'Save seating plan'}).click()]);
    assert.match(await t.locator('[data-seat="2"]').innerText(),/BrowserAllowed/);
    await t.locator('#rf-action-student').selectOption({label:'Fictional, BrowserAllowed'});
    await t.locator('#rf-action-kind').selectOption('observe');
    await t.locator('[data-class-action=observe] select[name=category]').selectOption('engaged');
    await Promise.all([t.waitForNavigation(),t.getByRole('button',{name:'Record observation'}).click()]);
    assert.match(await t.locator('#observations').innerText(),/engaged/);
    await t.locator('#rf-action-student').selectOption({label:'Fictional, BrowserAllowed'});
    await t.locator('#rf-action-kind').selectOption('task');
    await t.locator('[data-class-action=task] select[name=category]').selectOption('practice');
    await t.locator('[data-class-action=task] select[name=recipient]').selectOption({label:'browser_aide'});
    await Promise.all([t.waitForNavigation(),t.getByRole('button',{name:'Assign task',exact:true}).click()]);
    const aide=await browser.newContext(),ap=await login(aide,'browser_aide');
    await ap.goto(url+'/live/support/?view=tasks');
    assert.match(await ap.locator('main').innerText(),/BrowserAllowed/);
    await Promise.all([ap.waitForNavigation(),ap.getByRole('button',{name:'Accept task'}).click()]);
    await Promise.all([ap.waitForNavigation(),ap.getByRole('button',{name:'Complete task'}).click()]);
    assert.match(await ap.locator('main').innerText(),/completed/);
    await o.goto(url+'/live/support/');
    assert.doesNotMatch(await o.locator('main').innerText(),/BrowserAllowed/);
    await aide.close();
    const issue='/live/movements/issue/?code=BROWSER7&period=P1&start=00%3A00';
    assert.equal((await t.goto(url+issue)).status(),200);
    await t.locator('select[name=student]').selectOption({label:'Fictional, BrowserAllowed'});
    await t.locator('select[name=destination]').selectOption(await t.locator('select[name=destination] option').filter({hasText:'Fictional CI water break'}).getAttribute('value'));
    assert.match(await t.locator('#rf-movement-review').innerText(),/Review:.*BrowserAllowed/);
    await t.locator('input[name=confirm]').check();
    await t.locator('select[name=destination]').dispatchEvent('change');
    assert.equal(await t.locator('input[name=confirm]').isChecked(),false,'changed destination clears confirmation');
    await t.locator('input[name=confirm]').check();
    await Promise.all([t.waitForURL(/\/live\/movements\/\d+\/$/),t.getByRole('button',{name:'Issue and record departure'}).click()]);
    const movement=t.url();
    assert.equal((await o.goto(movement)).status(),404);
    await Promise.all([t.waitForNavigation(),t.getByRole('button',{name:'Confirm classroom return'}).click()]);
    await t.getByRole('link',{name:'View student day'}).click();
    assert.match(await t.locator('main').innerText(),/P1/);
    assert.match(await t.locator('main').innerText(),/Fictional CI water break/);
    assert.equal((await o.goto(t.url())).status(),404);
    await t.goto(url+'/live/teacher/students/');
    await t.getByRole('link',{name:'View student'}).click();
    assert.match(await t.locator('main').innerText(),/Fictional CI water break/);
    await t.getByRole('link',{name:'Open filtered movement register'}).click();
    assert(await t.locator('#rf-movement-search').isVisible());
    await t.locator('#rf-movement-query').fill('zz-no-match');
    assert.match(await t.locator('#rf-movement-search-status').innerText(),/0 matching displayed passes/);
    console.log('Protected installed app: independent sessions, roster isolation, submitted roll and monitor verified.');
  }finally{await browser.close();}
})().catch(e=>{console.error(e.message);process.exitCode=1;});
