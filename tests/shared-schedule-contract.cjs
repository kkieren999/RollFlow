const assert=require("node:assert/strict");
const core=require("../shared/schedule-core.js");
const day="2026-11-26";
const row={date:day,code:"MAT7",title:"Maths <script>",period:"P1",time:"09:00–10:00",room:"A",staff_id:"PRIVATE",student:"PRIVATE"};
const provider=core.provider(()=>({version:1,days:[{date:day,lessons:[row]}]}));
const snapshot=provider.getSchedule();
assert.equal(snapshot.days[0].lessons[0].title,row.title);
assert.equal(snapshot.days[0].lessons[0].staff_id,undefined);
assert.equal(snapshot.days[0].lessons[0].student,undefined);
assert(Object.isFrozen(snapshot.days[0].lessons[0]));
assert(core.heading(row).includes("Maths &lt;script&gt;"));
assert(!core.heading(row).includes("<script>"));
assert.throws(()=>core.snapshot({version:2,days:[]}));
assert.throws(()=>core.snapshot({version:1,days:[{date:day,lessons:[{...row,date:"2026-11-27"}]}]}));
assert.throws(()=>core.lesson({...row,date:"2026-02-30"}));
assert.throws(()=>core.snapshot({version:1,days:[{date:day,lessons:[]},{date:day,lessons:[]}]}));
assert.throws(()=>core.lesson({...row,code:""}));
const matching={dataset:{date:day,code:row.code,period:row.period,time:row.time},innerHTML:""};
const other={dataset:{date:day,code:"OTHER",period:row.period,time:row.time},innerHTML:"unchanged"};
core.mount({querySelectorAll:()=>[matching,other]},provider);
assert(matching.innerHTML.includes("MAT7"));
assert.equal(other.innerHTML,"unchanged");
assert.deepEqual(core.provider(()=>({version:1,days:[]})).getSchedule().days,[]);
console.log("PASS shared schedule contract, safe projection, rendering, isolation and validation");
